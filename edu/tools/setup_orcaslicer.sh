#!/usr/bin/env bash
# Install/refresh OrcaSlicer for the TonyPi print chain.
#
# Why this script is glibc-aware: since v2.3.1 the project ships ONLY an
# AppImage built on Ubuntu 24.04, which hard-requires GLIBC_2.38 and
# GLIBCXX_3.4.32. On Ubuntu 22.04 (glibc 2.35) it dies at exec with
# "version `GLIBC_2.38' not found". v2.3.0 is the last release that also
# published a 22.04-compatible AppImage, so that is what we pin there.
#
# Idempotent: re-running re-verifies and only downloads what is missing.
set -euo pipefail

APPDIR="${APPDIR:-$HOME/Applications}"
REPO="OrcaSlicer/OrcaSlicer"           # NOTE: moved from SoftFever/OrcaSlicer
DESKTOP_DIR="$HOME/.local/share/applications"
ICON_DIR="$HOME/.local/share/icons"

log() { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
die() { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- glibc gate
glibc_ver="$(ldd --version | head -1 | grep -oE '[0-9]+\.[0-9]+$')"
glibc_major="${glibc_ver%%.*}"
glibc_minor="${glibc_ver##*.}"
log "detected glibc $glibc_ver"

if [ "$glibc_major" -gt 2 ] || { [ "$glibc_major" -eq 2 ] && [ "$glibc_minor" -ge 38 ]; }; then
    # New enough for the current Ubuntu 24.04 AppImages -> take the latest release.
    log "glibc >= 2.38: eligible for the latest release"
    TAG="$(curl -sSL -H 'Accept: application/vnd.github+json' \
             "https://api.github.com/repos/$REPO/releases/latest" \
           | grep -m1 '"tag_name"' | cut -d'"' -f4)"
    [ -n "$TAG" ] || die "could not resolve latest tag from the GitHub API"
    ASSET="OrcaSlicer_Linux_AppImage_Ubuntu2404_${TAG}.AppImage"
else
    # Ubuntu 22.04 and older: v2.3.0 is the newest that still runs.
    log "glibc < 2.38: pinning v2.3.0, the last 22.04-compatible AppImage"
    TAG="v2.3.0"
    ASSET="OrcaSlicer_Linux_AppImage_V2.3.0.AppImage"
fi

TARGET="$APPDIR/OrcaSlicer_${TAG}.AppImage"
URL="https://github.com/$REPO/releases/download/$TAG/$ASSET"

# ------------------------------------------------------------------- libfuse2
if ! ls /usr/lib/*/libfuse.so.2 >/dev/null 2>&1; then
    cat >&2 <<'EOF'
WARNING: libfuse.so.2 not found. AppImage type-2 needs FUSE 2 to self-mount.
         Install it with:  sudo apt install libfuse2
         (or run the AppImage with --appimage-extract-and-run)
EOF
fi

# ------------------------------------------------------------------- download
mkdir -p "$APPDIR"
if [ -x "$TARGET" ] && [ "$(stat -c%s "$TARGET")" -gt 50000000 ]; then
    log "already present: $TARGET"
else
    log "downloading $ASSET"
    curl -fSL --retry 3 --progress-bar -o "$TARGET.part" "$URL"
    mv "$TARGET.part" "$TARGET"
    chmod +x "$TARGET"
fi

# Reject a truncated/HTML download: AppImage type 2 == ELF magic + "AI\x02" at 0x08.
magic="$(head -c 12 "$TARGET" | od -An -tx1 | tr -d ' \n')"
case "$magic" in
    7f454c46*4149020*) log "AppImage magic OK" ;;
    *) die "$TARGET is not a valid type-2 AppImage (magic: $magic)" ;;
esac

# --------------------------------------------------------------- x11 launcher
# OrcaSlicer's 3D canvas is wxWidgets/GTK3 + OpenGL. Under a native Wayland
# session that path is unreliable here, so the wrapper forces XWayland.
LAUNCHER="$APPDIR/orcaslicer"
cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Generated by edu/tools/setup_orcaslicer.sh -- do not edit by hand.
export GDK_BACKEND=x11
unset WAYLAND_DISPLAY
exec "$TARGET" "\$@"
EOF
chmod +x "$LAUNCHER"
log "launcher: $LAUNCHER"

# ------------------------------------------------------------- desktop  entry
mkdir -p "$DESKTOP_DIR" "$ICON_DIR"
if [ ! -f "$ICON_DIR/OrcaSlicer.png" ]; then
    tmp="$(mktemp -d)"
    ( cd "$tmp" && "$TARGET" --appimage-extract 'OrcaSlicer.png' >/dev/null 2>&1 \
      && cp squashfs-root/OrcaSlicer.png "$ICON_DIR/OrcaSlicer.png" ) || true
    rm -rf "$tmp"
fi
cat > "$DESKTOP_DIR/OrcaSlicer.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=OrcaSlicer
Comment=FDM slicer (TonyPi frame parts)
Exec=$LAUNCHER %F
Icon=$ICON_DIR/OrcaSlicer.png
Terminal=false
Categories=Graphics;3DGraphics;Engineering;
MimeType=model/stl;application/vnd.ms-3mfdocument;model/3mf;application/step;
StartupWMClass=OrcaSlicer
EOF
update-desktop-database "$DESKTOP_DIR" >/dev/null 2>&1 || true
log "desktop entry: $DESKTOP_DIR/OrcaSlicer.desktop"

# ------------------------------------------------------------------- verify
log "verifying the binary actually starts"
if "$TARGET" --help >/dev/null 2>"$APPDIR/.orca_verify.err"; then
    ver="$("$TARGET" --help 2>/dev/null | grep -m1 -oE 'OrcaSlicer-[0-9.]+' || echo unknown)"
    log "OK -- $ver  ($TAG)"
else
    printf '\033[1;31mFAILED to start.\033[0m stderr:\n' >&2
    cat "$APPDIR/.orca_verify.err" >&2
    exit 1
fi

cat <<EOF

Launch with:   $LAUNCHER
           or: the OrcaSlicer entry in your application menu

Print sources: edu/print_files/step/   (native STEP import -- keeps M3 holes exact)
               edu/print_files/stl/    (0.01 mm chord-tolerance meshes)
EOF
